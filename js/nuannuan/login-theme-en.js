export function localizePack(pack, lang) {
  if (!pack || lang !== "en") return pack;
  const en = PACK_EN[pack.key];
  if (!en) return pack;
  return {
    ...pack,
    outfit: en.outfit || pack.outfit,
    slogan: en.slogan || pack.slogan,
    accessories: pack.accessories.map((a) => ({ ...a, ...(ITEM_EN[a.id] || {}) })),
    marks: pack.marks.map((m) => ({ ...m, ...(ITEM_EN[m.id] || {}) })),
    eyes: pack.eyes.map((e) => ({ ...e, ...(ITEM_EN[e.id] || {}) })),
    keywords: pack.keywords.map((k) => ({ ...k, ...(ITEM_EN[k.id] || {}) })),
  };
}
