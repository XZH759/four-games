const listeners = new Set();

function normalize(lang) {
  if (!lang) return "zh";
  const s = String(lang).toLowerCase();
  if (s.startsWith("en")) return "en";
  if (s.startsWith("zh")) return "zh";
  return SUPPORTED.includes(s) ? s : "zh";
}

export function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved) return normalize(saved);
  } catch (_) {}
  return "zh";
}

export function t(key, vars = {}) {
  const lang = getLang();
  let str = DICT[lang]?.[key] ?? DICT.zh[key] ?? key;
  Object.entries(vars).forEach(([k, v]) => {
    str = str.replaceAll(`{${k}}`, String(v));
  });
  return str;
}

export function setLang(lang) {
  const next = normalize(lang);
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch (_) {}
  document.documentElement.lang = next === "en" ? "en" : "zh-CN";
  document.documentElement.dataset.lang = next;
  applyDom();
  syncToggles();
  listeners.forEach((cb) => {
    try {
      cb(next);
    } catch (_) {}
  });
  return next;
}

export function onLangChange(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

function fillTemplate(el, value) {
  if (!el || value == null) return;
  const attr = el.getAttribute("data-i18n-attr");
  if (attr) {
    attr.split(",").map((a) => a.trim()).filter(Boolean).forEach((name) => {
      el.setAttribute(name, value);
    });
    return;
  }
  if (el.hasAttribute("data-i18n-html")) {
    el.innerHTML = value;
    return;
  }
  el.textContent = value;
}

export function applyDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    fillTemplate(el, t(key));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  const titleEl = document.querySelector("title[data-i18n]");
  if (titleEl) document.title = t(titleEl.getAttribute("data-i18n"));
}

function syncToggles() {
  const lang = getLang();
  document.querySelectorAll("[data-lang-toggle]").forEach((wrap) => {
    wrap.querySelectorAll("[data-set-lang]").forEach((btn) => {
      const on = btn.getAttribute("data-set-lang") === lang;
      btn.classList.toggle("is-on", on);
      btn.setAttribute("aria-pressed", on ? "true" : "false");
    });
  });
}

/** Mount a compact ZH | EN control into a host element or before a selector. */
export function mountLangToggle(host, { compact = true } = {}) {
  const el =
    typeof host === "string" ? document.querySelector(host) : host;
  if (!el) return null;

  let wrap = el.querySelector(":scope > .lang-toggle");
  if (!wrap) {
    wrap = document.createElement("div");
    wrap.className = "lang-toggle" + (compact ? " is-compact" : "");
    wrap.setAttribute("data-lang-toggle", "");
    wrap.setAttribute("role", "group");
    wrap.setAttribute("aria-label", "Language");
    wrap.innerHTML = `
      <button type="button" class="lang-btn" data-set-lang="zh" aria-pressed="false">中</button>
      <button type="button" class="lang-btn" data-set-lang="en" aria-pressed="false">EN</button>
    `;
    el.appendChild(wrap);
    wrap.addEventListener("click", (e) => {
      const btn = e.target.closest("[data-set-lang]");
      if (!btn) return;
      setLang(btn.getAttribute("data-set-lang"));
    });
  }
  syncToggles();
  return wrap;
}

export function initI18n(options = {}) {
  const lang = getLang();
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  document.documentElement.dataset.lang = lang;
  applyDom();
  if (options.toggleHost) mountLangToggle(options.toggleHost, options);
  syncToggles();
  return lang;
}

